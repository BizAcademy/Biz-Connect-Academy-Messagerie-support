import assert from "node:assert/strict";
import { client } from "./helpers.mjs";
const admin = await client("admin"), member = await client("member");
const rows = (await admin.call("/conversations")).data;
assert(rows.length >= 3);
const target = rows[0];
let result = await admin.call(`/conversations/${target.id}`, { favorite: !target.favorite }, "PATCH");
assert.equal(result.status, 200);
assert((await admin.call("/conversations?filter=" + (!target.favorite ? "favorites" : "all"))).data.some((c) => c.id === target.id));
await admin.call(`/conversations/${target.id}`, { favorite: target.favorite }, "PATCH");
assert.equal((await admin.call("/conversations?search=doesnotexist")).data.length, 0);
assert((await admin.call("/conversations?search=" + encodeURIComponent(target.username))).data.some((c) => c.id === target.id));
const summary = (await admin.call("/conversations/summary")).data;
assert.equal(summary.total, rows.length);
assert.equal(summary.read + summary.unread, summary.total);
for (const filter of ["read", "unread", "favorites"]) assert.equal((await admin.call("/conversations?filter=" + filter)).status, 200);
const memberId = (await member.call("/conversations")).data[0].id;
assert.equal((await member.call(`/conversations/${memberId}`, { favorite: true }, "PATCH")).status, 403);
console.log("STAGE 4 PASS: inbox search, filters, summary, persistent favorites, admin-only mutation");
