import assert from "node:assert/strict";
import { client, base } from "./helpers.mjs";
import sharp from "sharp";
const member = await client("member");
const id = (await member.call("/conversations")).data[0].id;
const png = await sharp({ create: { width: 16, height: 16, channels: 3, background: "#1E5EFF" } }).png().toBuffer();
const upload = async (bytes, purpose, mime, name) => {
  const form = new FormData(); form.append("purpose", purpose); form.append("conversationId", id);
  form.append("file", new Blob([bytes], { type: mime }), name);
  return member.call("/files", form);
};
const image = await upload(png, "image", "image/png", "test.png");
assert.equal(image.status, 201, JSON.stringify(image.data));
assert.equal((await fetch(base + image.data.url)).status, 401);
const privateImage = await fetch(base + image.data.url, { headers: { cookie: member.cookie } });
assert.equal(privateImage.status, 200);
assert.equal(privateImage.headers.get("content-type"), "image/webp");
assert.equal((await member.call(`/conversations/${id}/messages`, { type: "image", fileId: image.data.id })).status, 201);
assert.equal((await upload(Buffer.from("<svg onload='alert(1)'/>"), "image", "image/png", "fake.png")).status, 415);
const wav = Buffer.alloc(44 + 16000 * 2);
wav.write("RIFF", 0); wav.writeUInt32LE(wav.length - 8, 4); wav.write("WAVEfmt ", 8);
wav.writeUInt32LE(16, 16); wav.writeUInt16LE(1, 20); wav.writeUInt16LE(1, 22);
wav.writeUInt32LE(16000, 24); wav.writeUInt32LE(32000, 28); wav.writeUInt16LE(2, 32); wav.writeUInt16LE(16, 34);
wav.write("data", 36); wav.writeUInt32LE(32000, 40);
const voice = await upload(wav, "voice", "audio/wav", "test.wav");
assert.equal(voice.status, 201, JSON.stringify(voice.data));
const msg = await member.call(`/conversations/${id}/messages`, { type: "voice", fileId: voice.data.id, duration: 299 });
assert.equal(msg.status, 201);
assert(Math.abs(msg.data.duration - 1) < 0.05, "duration must be derived from actual audio, not client");
const ranged = await fetch(base + voice.data.url, { headers: { cookie: member.cookie, range: "bytes=0-43" } });
assert.equal(ranged.status, 206); assert.equal((await ranged.arrayBuffer()).byteLength, 44);
const avatar = await upload(png, "avatar", "image/png", "avatar.png");
assert.equal(avatar.status, 201);
assert.equal((await member.call("/profile", { avatarFileId: avatar.data.id }, "PATCH")).status, 200);
