import assert from "node:assert/strict";
import { client } from "./helpers.mjs";
const member = await client("member"), admin = await client("admin");
const convs = await member.call("/conversations");
assert.equal(convs.status, 200, JSON.stringify(convs.data));
assert.equal(convs.data.length, 1);
const id = convs.data[0].id;
const result = await member.call(`/conversations/${id}/messages`, { type: "text", content: "Vérification technique : messagerie temps réel." });
assert.equal(result.status, 201);
assert.equal(result.data.status, "sent");
let rows = (await admin.call(`/conversations/${id}/messages`)).data;
assert.equal(rows.find((m) => m.id === result.data.id).status, "delivered");
assert.equal((await admin.call(`/conversations/${id}/read`, {})).status, 200);
rows = (await member.call(`/conversations/${id}/messages`)).data;
assert.equal(rows.find((m) => m.id === result.data.id).status, "read");
const other = (await admin.call("/conversations")).data.find((c) => c.id !== id);
assert.equal((await member.call(`/conversations/${other.id}/messages`)).status, 404);
assert.equal((await member.call(`/conversations/${id}/messages`, { type: "text", content: " " })).status, 400);
console.log("STAGE 2 PASS: persisted text, ownership, empty-message rejection, sent/delivered/read receipts");
console.log("cleanupMessageId=" + result.data.id);
