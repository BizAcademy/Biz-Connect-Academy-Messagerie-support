import assert from "node:assert/strict";
import { client, base } from "./helpers.mjs";
const member = await client("member");
const manifestResponse = await fetch(base + "/manifest.webmanifest");
assert.equal(manifestResponse.status, 200);
const manifest = await manifestResponse.json();
assert.equal(manifest.display, "standalone"); assert.equal(manifest.start_url, "/");
for (const icon of manifest.icons) assert.equal((await fetch(base + icon.src)).status, 200);
assert((await (await fetch(base + "/sw.js")).text()).includes('self.addEventListener("push"'));
const config = await member.call("/push/config");
assert.equal(config.status, 200);
if (config.data.enabled) assert.equal(typeof config.data.publicKey, "string");
assert.equal((await member.call("/push/subscriptions", { endpoint: "https://127.0.0.1/admin", keys: { p256dh: "fake", auth: "fake" } })).status, config.data.enabled ? 400 : 503);
let r = await fetch(base + "/api/auth/demo", { method: "POST", headers: { cookie: member.cookie, "content-type": "application/json" }, body: '{"role":"admin"}' });
assert.equal(r.status, 403);
r = await fetch(base + "/api/auth/session", { headers: { origin: "https://untrusted.example" } });
assert.equal(r.status, 403);
r = await fetch(base + "/api/conversations");
assert.equal(r.status, 401);
assert.equal(r.headers.get("x-content-type-options"), "nosniff");
const logout = await member.call("/auth/logout", {});
assert.equal(logout.status, 200);
assert.equal((await member.call("/conversations")).status, 401);
console.log("STAGES 5/6 PASS: manifest/icons/SW, push config, SSRF guard, CSRF, foreign origin, authentication, security headers, logout revocation");
